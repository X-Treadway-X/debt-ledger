/** Looks up a string for the current language: tr("save"), tr("t_debt_saved", "n" to name). */
class Tr(val lang: String) {
    val isAr: Boolean get() = lang == "ar"

    operator fun invoke(key: String, vararg args: Pair<String, String>): String {
        var s = (if (lang == "ar") AR[key] else EN[key]) ?: key
        for ((k, v) in args) s = s.replace("{" + k + "}", v)
        return s
    }
}
